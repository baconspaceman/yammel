import { describe, expect, it } from 'vitest';
import { YamlDocument } from './document';
import { EditError } from './edits';

const SAMPLE = `# header comment
name: Bacon # my slot name
description: Generated by hand
game: Demo Game
Demo Game:
  lives: 5
`;

describe('getMeta', () => {
  it('reads the name and description', () => {
    const doc = YamlDocument.parse(SAMPLE);
    expect(doc.getMeta('name')).toBe('Bacon');
    expect(doc.getMeta('description')).toBe('Generated by hand');
  });

  it('is undefined when the key is missing or not a plain value', () => {
    expect(YamlDocument.parse('game: G\n').getMeta('name')).toBeUndefined();
    expect(YamlDocument.parse('name:\n  a: 1\n').getMeta('name')).toBeUndefined();
    expect(YamlDocument.parse('').getMeta('name')).toBeUndefined();
  });

  it('shows a number-looking name as text', () => {
    expect(YamlDocument.parse('name: 123\n').getMeta('name')).toBe('123');
  });
});

describe('setMeta', () => {
  it('replaces the name and keeps its trailing comment', () => {
    const doc = YamlDocument.parse(SAMPLE);
    doc.apply({ op: 'setMeta', key: 'name', value: 'Spaceman' });
    expect(doc.toString()).toContain('name: Spaceman # my slot name');
    expect(doc.toString()).toContain('# header comment');
    expect(doc.get('Demo Game', 'lives')).toBe(5);
  });

  it('adds a missing description', () => {
    const doc = YamlDocument.parse('name: P\ngame: G\n');
    doc.apply({ op: 'setMeta', key: 'description', value: 'Hello' });
    expect(doc.getMeta('description')).toBe('Hello');
  });

  it('removes the description when set to an empty string', () => {
    const doc = YamlDocument.parse(SAMPLE);
    doc.apply({ op: 'setMeta', key: 'description', value: '' });
    expect(doc.getMeta('description')).toBeUndefined();
    expect(doc.toString()).not.toContain('Generated by hand');
  });

  it('refuses an empty or blank name', () => {
    const doc = YamlDocument.parse(SAMPLE);
    expect(() => doc.apply({ op: 'setMeta', key: 'name', value: '' })).toThrow(EditError);
    expect(() => doc.apply({ op: 'setMeta', key: 'name', value: '   ' })).toThrow(EditError);
    expect(doc.getMeta('name')).toBe('Bacon');
  });

  it('writes text that looks like a boolean or number as text', () => {
    const doc = YamlDocument.parse(SAMPLE);
    doc.apply({ op: 'setMeta', key: 'name', value: 'yes' });
    expect(YamlDocument.parse(doc.toString()).getMeta('name')).toBe('yes');
    doc.apply({ op: 'setMeta', key: 'name', value: '123' });
    expect(YamlDocument.parse(doc.toString()).getMeta('name')).toBe('123');
  });

  it('works on an empty document and refuses a non-map top level', () => {
    const doc = YamlDocument.parse('');
    doc.apply({ op: 'setMeta', key: 'name', value: 'P' });
    expect(doc.getMeta('name')).toBe('P');
    const list = YamlDocument.parse('- a\n');
    expect(() => list.apply({ op: 'setMeta', key: 'name', value: 'P' })).toThrow(EditError);
  });
});
